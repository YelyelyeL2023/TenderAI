def method(tool: str, ru: str, lang: str) -> str:
    return METHOD_KK.get(tool, ru) if lang == "kk" else ru


def limitation(text: str, lang: str) -> str:
    if lang != "kk":
        return text
    for rx, kk in PATTERNS_KK:
        m = re.match(rx, text)
        if m:
            return kk.format(*m.groups())
    for prefix, kk in LIMITS_KK:
        if text.startswith(prefix):
            tail = text[text.find("(источник:"):] if "(источник:" in text else ""
            return f"{kk} {tail.replace('источник', 'дереккөз')}".strip()
    return text
